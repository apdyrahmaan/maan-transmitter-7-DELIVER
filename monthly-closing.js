// Closes finished months (Mogadishu time): records totals, adds a system report,
// and locks that month's records against edits until an admin reopens it.
const { readDatabase, saveDatabase, generateId, currentDate } = require("./database");
const { mogadishuDateKey } = require("./backups");

function periodOf(record) {
    const value = record && (record.date || record.createdAt);
    if (!value) return null;
    const date = new Date(value);
    return Number.isNaN(date.getTime()) ? null : mogadishuDateKey(date).slice(0, 7);
}

function closeFinishedMonths(now = new Date()) {
    const database = readDatabase();
    const currentPeriod = mogadishuDateKey(now).slice(0, 7);
    const periods = new Set();
    for (const name of ["orders", "payments", "expenses", "deliveries", "shipments"]) {
        database[name].forEach(record => {
            const period = periodOf(record);
            if (period && period < currentPeriod) periods.add(period);
        });
    }

    const closed = [];
    for (const period of [...periods].sort()) {
        if (database.monthlyClosings.some(item => item.period === period)) continue; // closed or reopened by admin
        const inPeriod = name => database[name].filter(record => periodOf(record) === period);
        const revenue = inPeriod("payments").reduce((sum, item) => sum + Number(item.amount || 0), 0);
        const expenses = inPeriod("expenses").reduce((sum, item) => sum + Number(item.amount || 0), 0);
        const orders = inPeriod("orders").length;
        const closing = {
            period,
            status: "closed",
            revenue,
            expenses,
            profit: revenue - expenses,
            orders,
            closedAt: currentDate()
        };
        database.monthlyClosings.push(closing);
        database.reports.push({
            id: generateId("REP"),
            title: `Xisaab-xir ${period}`,
            category: "Finance",
            status: "Final",
            summary: `Orders: ${orders}. Revenue: ${revenue.toFixed(2)}. Expenses: ${expenses.toFixed(2)}. Profit: ${(revenue - expenses).toFixed(2)}.`,
            autoGenerated: "monthly-closing",
            createdAt: currentDate()
        });
        closed.push(period);
    }
    if (closed.length) saveDatabase(database);
    return closed;
}

module.exports = { closeFinishedMonths };
