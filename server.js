// On Netlify the serverless adapter supplies the raw body as a Buffer, which
// express.json() skips, so parse it here.
app.use((req, res, next) => {
    if (!Buffer.isBuffer(req.body)) return next();
    const raw = req.body;
    req.body = {};
    if (!raw.length || !/json/i.test(req.headers["content-type"] || "")) return next();
    if (raw.length > 6 * 1024 * 1024) {
        return res.status(413).json({ success: false, message: "Xogta la diray aad ayay u weyn tahay." });
    }
    try {
        req.body = JSON.parse(raw.toString("utf8"));
    } catch (error) {
        return res.status(400).json({ success: false, message: "JSON-ka la diray waa khalad." });
    }
    next();
});

