app.post("/api/register", async (req, res) => {
    const database = readDatabase();
    const name = String(req.body?.name || "").trim();
    const phone = String(req.body?.phone || "").trim();
    const email = String(req.body?.email || "").trim();
    const username = String(req.body?.username || "").trim();
    const password = req.body?.password;

    // The first account becomes the administrator. After that, only allow
    // self-registration if the admin has enabled it in settings.
    const isFirstUser = database.users.length === 0;
    if (!isFirstUser && database.settings.allowRegistration !== true) {
        return fail(res, 403, "Is-diiwaangelinta waa xiran tahay. Admin-ka ha kuu sameeyo akoon.");
    }
    if (!name || !phone || !validEmail(email)) return fail(res, 400, "Geli magac, telefoon iyo email sax ah.");
    if (!/^[a-z0-9._-]{3,30}$/i.test(username)) return fail(res, 400, "Username-ku waa khalad.");
    if (typeof password !== "string" || password.length < 8) {
        return fail(res, 400, "Password-ku waa inuu ahaado ugu yaraan 8 xaraf.");
    }
    if (emailTaken(database, email)) return fail(res, 409, "Email-kan horay ayaa loo isticmaalay.");
    if (database.users.some(user => String(user.username || "").toLowerCase() === username.toLowerCase())) {
        return fail(res, 409, "Username-kan horay ayaa loo isticmaalay.");
    }

    const user = {
        id: generateId("USR"),
        name,
        email,
        username,
        phone,
        password: await bcrypt.hash(password, 12),
        role: isFirstUser ? "admin" : "staff",
        avatar: "",
        createdAt: currentDate()
    };
    database.users.push(user);
    saveDatabase(database);
    res.status(201).json({ ...createSession(user), message: "Akoonka waa la sameeyay." });
});

