const SETTINGS_FIELDS = [
    "companyName", "country", "currency", "phone", "email", "website", "edahabNumber",
    "edahabAltNumber", "paymentTemplate", "logo", "cashierImage", "companyPhone",
    "businessAddress", "merchantAddress", "businessDetails", "allowRegistration"
];

function applySettings(settings, body) {
    for (const field of SETTINGS_FIELDS) {
        if (body[field] === undefined) continue;
        if (field === "allowRegistration") settings[field] = body[field] === true;
        else settings[field] = String(body[field] ?? "").slice(0, field === "logo" || field === "cashierImage" ? 3_000_000 : 5000);
    }
    if (body.menuItems && typeof body.menuItems === "object") {
        for (const [key, label] of Object.entries(body.menuItems)) {
            if (key in settings.menuItems && typeof label === "string" && label.trim()) {
                settings.menuItems[key] = label.trim().slice(0, 40);
            }
        }
    }
}

