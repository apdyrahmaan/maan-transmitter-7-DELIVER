const ROUTES = {
    customers: "customers",
    orders: "orders",
    payments: "payments",
    deliveries: "deliveries",
    shipments: "shipments",
    expenses: "expenses",
    reports: "reports",
    "monthly-bills": "monthlyBills"
};

const REQUIRED_FIELDS = {
    customers: ["name"],
    orders: ["customerName"],
    payments: ["customerName", "amount"],
    deliveries: ["customerName"],
    shipments: ["trackingNumber"],
    expenses: ["amount"],
    reports: ["title"],
    monthlyBills: []
};

for (const [route, collection] of Object.entries(ROUTES)) {
    app.get(`/api/${route}`, (req, res) => {
        res.json({ success: true, data: readDatabase()[collection] });
    });

    app.get(`/api/${route}/:id`, (req, res) => {
        const record = readDatabase()[collection].find(item => item.id === req.params.id);
        if (!record) return fail(res, 404, "Diiwaanka lama helin.");
        res.json({ success: true, data: record });
    });

    app.post(`/api/${route}`, (req, res) => {
        const database = readDatabase();
        const payload = cleanPayload(req.body);
        const missing = REQUIRED_FIELDS[collection].find(field => payload[field] === undefined || payload[field] === "");
        if (missing) return fail(res, 400, `Fadlan buuxi: ${missing}.`);
        const now = currentDate();
        const record = {
            id: generateId(COLLECTIONS[collection]),
            ...payload,
            ...(collection === "payments" && !payload.date ? { date: now } : {}),
            createdBy: req.user.id,
            createdAt: now
        };
        if (isPeriodClosed(database, periodOf(record))) return fail(res, 423, lockedMessage(periodOf(record)));
        database[collection].push(record);
        saveDatabase(database);
        res.status(201).json({ success: true, message: "Waa la kaydiyay.", data: record });
    });

    app.put(`/api/${route}/:id`, (req, res) => {
        const database = readDatabase();
        const index = database[collection].findIndex(item => item.id === req.params.id);
        if (index === -1) return fail(res, 404, "Diiwaanka lama helin.");
        const existing = database[collection][index];
        if (existing.autoGenerated) return fail(res, 403, "Diiwaankan nidaamka ayaa sameeyay, lama beddeli karo.");
        if (isPeriodClosed(database, periodOf(existing))) return fail(res, 423, lockedMessage(periodOf(existing)));
        const updated = { ...existing, ...cleanPayload(req.body), updatedAt: currentDate() };
        if (isPeriodClosed(database, periodOf(updated))) return fail(res, 423, lockedMessage(periodOf(updated)));
        database[collection][index] = updated;
        saveDatabase(database);
        res.json({ success: true, message: "Waa la cusbooneysiiyay.", data: updated });
    });

    app.delete(`/api/${route}/:id`, (req, res) => {
        const database = readDatabase();
        const index = database[collection].findIndex(item => item.id === req.params.id);
        if (index === -1) return fail(res, 404, "Diiwaanka lama helin.");
        const existing = database[collection][index];
        if (existing.autoGenerated) return fail(res, 403, "Diiwaankan nidaamka ayaa sameeyay, lama tirtiri karo.");
        if (isPeriodClosed(database, periodOf(existing))) return fail(res, 423, lockedMessage(periodOf(existing)));
        database[collection].splice(index, 1);
        if (collection === "orders") {
            database.deletedOrders.push({ ...existing, deletedAt: currentDate(), deletedBy: req.user.id });
        }
        saveDatabase(database);
        res.json({
            success: true,
            message: collection === "orders" ? "Order-ka ayaa loo raray recycle bin." : "Waa la tirtiray.",
            data: existing
        });
    });
}

