const COLLECTIONS = {
    customers: "CUS",
    orders: "ORD",
    payments: "PAY",
    deliveries: "DEL",
    shipments: "SHP",
    expenses: "EXP",
    reports: "REP",
    monthlyBills: "BIL"
};

const PROTECTED_FIELDS = new Set(["id", "createdAt", "updatedAt", "createdBy", "deletedAt", "autoGenerated"]);

function fail(res, status, message) {
    return res.status(status).json({ success: false, message });
}

function cleanPayload(body) {
    const result = {};
    if (!body || typeof body !== "object" || Array.isArray(body)) return result;
    for (const [key, value] of Object.entries(body)) {
        if (PROTECTED_FIELDS.has(key) || key.startsWith("__")) continue;
        if (value === null || ["string", "number", "boolean"].includes(typeof value)) {
            result[key] = typeof value === "string" ? value.slice(0, 5000) : value;
        }
    }
    return result;
}

function periodOf(record) {
    const value = record && (record.date || record.createdAt);
    if (!value) return null;
    const date = new Date(value);
    if (Number.isNaN(date.getTime())) return null;
    return mogadishuDateKey(date).slice(0, 7);
}

function isPeriodClosed(database, period) {
    return Boolean(period) && database.monthlyClosings.some(
        closing => closing.period === period && closing.status !== "reopened"
    );
}

function lockedMessage(period) {
    return `Bisha ${period} waa la xiray. Admin-ka ha dib u furo si diiwaanka loo beddelo.`;
}

function findUser(database, id) {
    return database.users.find(user => user.id === id);
}

function requireAuth(req, res, next) {
    const header = req.headers.authorization || "";
    const token = header.startsWith("Bearer ") ? header.slice(7) : "";
    if (!token) return fail(res, 401, "Fadlan marka hore login samee.");
    const payload = verifyToken(token);
    if (!payload) return fail(res, 401, "Login-ka wuu dhacay ama token-ku waa khalad.");
    const user = findUser(readDatabase(), payload.id);
    if (!user) return fail(res, 401, "Akoonkan lama helin. Fadlan mar kale login samee.");
    req.user = user;
    next();
}

function requireAdmin(req, res, next) {
    if (!req.user || req.user.role !== "admin") {
        return fail(res, 403, "Kaliya admin-ka ayaa samayn kara arrintan.");
    }
    next();
}

function emailTaken(database, email, exceptId) {
    const value = String(email || "").toLowerCase();
    return database.users.some(user => user.id !== exceptId && String(user.email || "").toLowerCase() === value);
}

const validEmail = value => /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(String(value || ""));

