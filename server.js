function updateProfile(database, user, body) {
    const name = String(body.name || "").trim();
    const email = String(body.email || "").trim();
    const phone = String(body.phone || "").trim();
    if (!name || !validEmail(email) || !phone) return "Magaca, email sax ah iyo telefoonka waa in la buuxiyaa.";
    if (emailTaken(database, email, user.id)) return "Email-kan akoon kale ayaa isticmaalaya.";
    user.name = name.slice(0, 200);
    user.email = email.slice(0, 200);
    user.phone = phone.slice(0, 50);
    if (typeof body.avatar === "string") user.avatar = body.avatar.slice(0, 3_000_000);
    user.updatedAt = currentDate();
    return null;
}

app.put("/api/admin/profile", (req, res) => {
    const database = readDatabase();
    const user = findUser(database, req.user.id);
    const error = updateProfile(database, user, req.body || {});
    if (error) return fail(res, 400, error);
    saveDatabase(database);
    res.json({ success: true, message: "Profile-ka waa la badalay.", data: publicUser(user) });
});

