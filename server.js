const EXPORT_COLLECTIONS = ["customers", "orders", "deletedOrders", "payments", "expenses", "deliveries", "shipments", "reports", "monthlyBills", "monthlyClosings"];

function exportRows(database) {
    return Object.fromEntries(EXPORT_COLLECTIONS.map(name => [name, database[name] || []]));
}

function columnsOf(rows) {
    const columns = new Set();
    rows.forEach(row => Object.keys(row).forEach(key => columns.add(key)));
    return [...columns];
}

function csvCell(value) {
    let text = value === undefined || value === null ? "" : String(value);
    if (/^[=+\-@\t\r]/.test(text)) text = `'${text}`; // spreadsheet formula injection guard
    return /[",\r\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

app.get("/api/admin/exports/:format", requireAdmin, async (req, res) => {
    const format = req.params.format;
    const data = exportRows(readDatabase());
    const stamp = mogadishuDateKey(new Date());

    if (format === "csv") {
        const sections = Object.entries(data).map(([name, rows]) => {
            const columns = columnsOf(rows);
            const lines = [`# ${name}`, columns.map(csvCell).join(",")];
            rows.forEach(row => lines.push(columns.map(column => csvCell(row[column])).join(",")));
            return lines.join("\r\n");
        });
        res.setHeader("Content-Type", "text/csv; charset=utf-8");
        res.setHeader("Content-Disposition", `attachment; filename="maan-full-data-${stamp}.csv"`);
        return res.send("﻿" + sections.join("\r\n\r\n"));
    }

    if (format === "xlsx") {
        const XLSX = require("xlsx");
        const workbook = XLSX.utils.book_new();
        for (const [name, rows] of Object.entries(data)) {
            const sheet = XLSX.utils.json_to_sheet(rows.length ? rows : [{ info: "No records" }]);
            XLSX.utils.book_append_sheet(workbook, sheet, name.slice(0, 31));
        }
        const buffer = XLSX.write(workbook, { type: "buffer", bookType: "xlsx" });
        res.setHeader("Content-Type", "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet");
        res.setHeader("Content-Disposition", `attachment; filename="maan-full-data-${stamp}.xlsx"`);
        return res.send(buffer);
    }

    if (format === "pdf") {
        const PDFDocument = require("pdfkit");
        const doc = new PDFDocument({ margin: 40, size: "A4" });
        const chunks = [];
        doc.on("data", chunk => chunks.push(chunk));
        const done = new Promise(resolve => doc.on("end", resolve));
        doc.fontSize(18).text(readDatabase().settings.companyName || "Maan Transmitter & Deliver");
        doc.fontSize(10).fillColor("#555").text(`Full data export - ${stamp}`).moveDown();
        for (const [name, rows] of Object.entries(data)) {
            doc.fillColor("#000").fontSize(14).text(`${name} (${rows.length})`).moveDown(0.3);
            doc.fontSize(8);
            rows.forEach(row => {
                const line = Object.entries(row)
                    .filter(([key, value]) => key !== "password" && !(typeof value === "string" && value.startsWith("data:")))
                    .map(([key, value]) => `${key}: ${value}`)
                    .join(" | ");
                doc.text(line).moveDown(0.2);
            });
            doc.moveDown();
        }
        doc.end();
        await done;
        res.setHeader("Content-Type", "application/pdf");
        res.setHeader("Content-Disposition", `attachment; filename="maan-full-data-${stamp}.pdf"`);
        return res.send(Buffer.concat(chunks));
    }

    fail(res, 400, "Qaabka export-ka lama taageero.");
});

